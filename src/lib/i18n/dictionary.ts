export type I18nKey = keyof typeof vi;

const dictionaries: Record<Language, Record<I18nKey, string>> = { vi, en };

export function hasKey(key: string): key is I18nKey {
  return key in dictionaries.vi;
}

export function translate(lang: Language, key: I18nKey, params?: Record<string, string | number>): string {
  let text: string = dictionaries[lang][key];
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
